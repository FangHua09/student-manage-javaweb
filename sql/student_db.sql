-- ============================================================
-- 学生信息管理系统 数据库脚本
-- 数据库：student_db   字符集：utf8mb4
-- 说明：直接执行本脚本即可建库、建表并写入测试数据
-- ============================================================

-- 说明：显式使用 utf8mb4_general_ci（而不是 MySQL 8 默认的 utf8mb4_0900_ai_ci），
--       避免不同小版本 MySQL 之间导入导出时排序规则不一致；课程项目不需要 0900 的排序特性。
CREATE DATABASE IF NOT EXISTS student_db
    DEFAULT CHARACTER SET utf8mb4
    DEFAULT COLLATE utf8mb4_general_ci;

USE student_db;

-- 先删外键表，再删主表
DROP TABLE IF EXISTS t_user;
DROP TABLE IF EXISTS t_student;

-- ------------------------------------------------------------
-- 表 3-1 学生信息表 t_student
-- ------------------------------------------------------------
CREATE TABLE t_student (
    stu_no     VARCHAR(20) NOT NULL                COMMENT '学号，主键',
    name       VARCHAR(20) NOT NULL                COMMENT '姓名',
    gender     CHAR(2)     NOT NULL DEFAULT '男'   COMMENT '性别',
    class_name VARCHAR(30)                         COMMENT '班级',
    major      VARCHAR(30)                         COMMENT '专业',
    phone      VARCHAR(15)                         COMMENT '联系电话',
    email      VARCHAR(50)                         COMMENT '电子邮箱',
    PRIMARY KEY (stu_no),
    KEY idx_student_name (name),
    KEY idx_student_class (class_name)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '学生信息表';

-- ------------------------------------------------------------
-- 表 3-2 用户表 t_user
-- role：0 = 管理员，1 = 学生
-- ------------------------------------------------------------
CREATE TABLE t_user (
    user_id  INT         NOT NULL AUTO_INCREMENT  COMMENT '用户主键，自增',
    username VARCHAR(30) NOT NULL                 COMMENT '登录账号，唯一',
    password VARCHAR(64) NOT NULL                 COMMENT '登录密码',
    role     TINYINT     NOT NULL DEFAULT 1       COMMENT '0为管理员，1为学生',
    stu_no   VARCHAR(20) DEFAULT NULL             COMMENT '关联学号，管理员为空',
    PRIMARY KEY (user_id),
    UNIQUE KEY uk_user_username (username),
    UNIQUE KEY uk_user_stu_no (stu_no),
    CONSTRAINT fk_user_student FOREIGN KEY (stu_no)
        REFERENCES t_student (stu_no) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '用户表';

